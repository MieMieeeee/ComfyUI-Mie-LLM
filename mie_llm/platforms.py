BY_KEY = {row["key"]: row for row in PLATFORMS}


def by_config_key(key):
    """The platform rows that read a given key entry."""
    return [row for row in PLATFORMS if row["key"] == key]


def connector_class(row):
    """The connector class for a platform row."""
    from mie_llm import client
    return getattr(client, row["connector"])
